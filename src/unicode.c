static i64 binary_search_u16(u16 c, const u16 *table, i64 length, i64 stride) {
    i64 n = length;
    i64 t = 0;
    while (n > 1) {
        i64 m = n / 2;
        i64 p = t + m * stride;
        if (c >= table[p]) {
            t = p;
            n = n - m;
        } else {
            n = m;
        }
    }

    if (n != 0 && c >= table[t]) {
        return t;
    }
    return -1;
}

static i64 binary_search_i32(i32 c, const i32 *table, i64 length, i64 stride) {
    i64 n = length;
    i64 t = 0;
    while (n > 1) {
        i64 m = n / 2;
        i64 p = t + m * stride;
        if (c >= table[p]) {
            t = p;
            n = n - m;
        } else {
            n = m;
        }
    }

    if (n != 0 && c >= table[t]) {
        return t;
    }
    return -1;
}

static bool in_range(Rune r, Range ra) {
    if (r <= 0xFFFF) {
        u16 r16 = r;

        i64 length = ra.ranges_16.count;
        i64 index = length > 0 ? binary_search_u16(r16, ra.ranges_16.data, length / 2, 2) : -1;
        if (index >= 0 && ra.ranges_16.data[index] <= r16 && ra.ranges_16.data[index + 1] >= r16) {
            return true;
        }

        length = ra.single_16.count;
        index = length > 0 ? binary_search_u16(r16, ra.single_16.data, length, 1) : -1;
        if (index >= 0 && ra.single_16.data[index] == r16) {
            return true;
        }
    }

    i32 r32 = r;
    i64 length = ra.ranges_32.count;
    i64 index = length > 0 ? binary_search_i32(r32, ra.ranges_32.data, length / 2, 2) : -1;
    if (index >= 0 && ra.ranges_32.data[index] <= r32 && ra.ranges_32.data[index + 1] >= r32) {
        return true;
    }

    length = ra.single_32.count;
    index = length > 0 ? binary_search_i32(r32, ra.single_32.data, length, 1) : -1;
    if (index >= 0 && ra.single_32.data[index] == r32) {
        return true;
    }

    return false;
}

bool rune_is_digit(Rune r) {
    if (r <= MAX_LATIN1) {
        return ('0' <= r && r <= '9') || r == 0x00B9 || (r >= 0x00B2 && r <= 0x0B3);
    }

    if (in_range(r, nd_ranges)) {
        return true;
    }

    if (in_range(r, extra_digits_ranges)) {
        return true;
    }

    return false;
}

bool rune_is_lower(Rune r) {
    if (r <= MAX_ASCII) {
        return (u32) r - (u32) 'a' < 26;
    }
    return in_range(r, ll_ranges) || in_range(r, other_lowercase_ranges);
}

bool rune_is_upper(Rune r) {
    if (r <= MAX_ASCII) {
        return (u32) r - (u32) 'A' < 26;
    }
    return in_range(r, lu_ranges) || in_range(r, other_uppercase_ranges);
}

bool rune_is_alpha(Rune r) {
    if ((u32) r <= (u32) MAX_LATIN1) {
        return (char_properties[(u8) r] & pLmask) != 0;
    }

    if (rune_is_upper(r) || rune_is_lower(r)) {
        return true;
    }

    const bool ll_lu = in_range(r, ll_ranges) || in_range(r, lu_ranges);
    return ll_lu || in_range(r, lo_ranges) || in_range(r, lt_ranges) || in_range(r, lm_ranges);
}

bool rune_is_number(Rune r) {
    if ((u32) r <= (u32) MAX_LATIN1) {
        return (char_properties[(u8) r] & pN) != 0;
    }

    return in_range(r, nd_ranges) || in_range(r, nl_ranges) || in_range(r, no_ranges);
}
